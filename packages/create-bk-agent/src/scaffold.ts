import * as fs from 'fs';
import * as path from 'path';
import { execSync } from 'child_process';
import type { UserChoices, ArchitectureId, DeployMode, SkillPack, ProviderId } from './prompts';

const TEMPLATES_DIR = path.resolve(__dirname, '../../templates');
const BASE_DIR      = path.join(TEMPLATES_DIR, 'base');
const DEPLOY_DIR    = path.join(TEMPLATES_DIR, 'deploy');

// Only these architectures use the base + deploy layer pattern.
// The rest (coding, autonomous, minimal) are self-contained in base/.
const LAYERED: ArchitectureId[] = ['multi-agent', 'single'];

// ── Provider env var hints ────────────────────────────────────────────────────

const PROVIDER_ENV: Record<ProviderId, { varName: string; placeholder: string; model: string }> = {
    anthropic: { varName: 'ANTHROPIC_API_KEY', placeholder: 'sk-ant-...',  model: 'claude-sonnet-4-6' },
    openai:    { varName: 'OPENAI_API_KEY',    placeholder: 'sk-...',      model: 'gpt-4o' },
    deepseek:  { varName: 'LLM_API_KEY',       placeholder: 'sk-...',      model: 'deepseek-chat' },
    ollama:    { varName: 'OLLAMA_BASE_URL',   placeholder: 'http://localhost:11434', model: 'llama3.2' },
};

// ── Copy directory (overlay-safe) ─────────────────────────────────────────────
// dst may already exist from the base layer — files are overwritten, dirs merged.

function copyDir(src: string, dst: string): void {
    fs.mkdirSync(dst, { recursive: true });
    for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
        const srcPath = path.join(src, entry.name);
        const dstPath = path.join(dst, entry.name);
        entry.isDirectory() ? copyDir(srcPath, dstPath) : fs.copyFileSync(srcPath, dstPath);
    }
}

// ── Patch package.json — name + scripts ──────────────────────────────────────

const DEPLOY_SCRIPTS: Partial<Record<DeployMode, (s: Record<string, string>) => void>> = {
    repl: (s) => {
        delete s['server'];
    },
    'mcp-http': (s) => {
        s['dev']   = 'ts-node src/server.ts';
        s['start'] = 'node dist/server.js';
        delete s['server'];
    },
    'mcp-stdio': (s) => {
        s['dev']   = 'ts-node src/server.ts';
        s['start'] = 'node dist/server.js';
        delete s['server'];
    },
    // hybrid: keep both dev (REPL) and server (MCP) — no changes
    library: (s) => {
        delete s['dev'];
        delete s['server'];
        delete s['start'];
    },
};

function patchPackageJson(
    dir:         string,
    projectName: string,
    deployMode:  DeployMode | undefined,
): void {
    const pkgPath = path.join(dir, 'package.json');
    if (!fs.existsSync(pkgPath)) return;

    const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8'));
    pkg.name = projectName;

    if (deployMode && DEPLOY_SCRIPTS[deployMode]) {
        pkg.scripts ??= {};
        DEPLOY_SCRIPTS[deployMode]!(pkg.scripts);
    }

    fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
}

// ── Write .env stub ───────────────────────────────────────────────────────────

function writeEnv(dir: string, provider: ProviderId): void {
    const envExample = path.join(dir, '.env.example');
    const envFile    = path.join(dir, '.env');
    if (!fs.existsSync(envExample) || fs.existsSync(envFile)) return;

    const p = PROVIDER_ENV[provider];
    const content = [
        '# Generated by create-bk-agent',
        `${p.varName}=${p.placeholder}`,
        `LLM_PROVIDER=${provider}`,
        `LLM_MODEL=${p.model}`,
        ...(provider !== 'anthropic' && provider !== 'ollama'
            ? ['LLM_BASE_URL=https://api.openai.com/v1']
            : []),
        '',
    ].join('\n');

    fs.writeFileSync(envFile, content);
}

// ── Inject skill pack hint into engine.ts ─────────────────────────────────────
// Appends a clearly marked comment block so the developer knows what to wire.
// Full YAML-based skill injection is handled by `create-bk-agent add skills`.

const SKILL_HINTS: Record<SkillPack, string> = {
    node:   'npm, jest, tsc, eslint — Node.js / TypeScript conventions',
    python: 'pytest, ruff, mypy, pip — Python conventions',
    go:     'go test, golangci-lint — Go conventions',
    docker: 'docker, kubectl, helm — Docker / K8s conventions',
};

function injectSkillPack(targetDir: string, pack: SkillPack): void {
    const engineFile = path.join(targetDir, 'src', 'engine.ts');
    if (!fs.existsSync(engineFile)) return;

    const block = [
        '',
        `// ── Skill pack: ${pack} ──────────────────────────────────────────────────────`,
        `// ${SKILL_HINTS[pack]}`,
        `// To activate: add YAML skill files in .backendkit-agent/skills/`,
        `// and wire SkillLoader + SkillActivator into the engine above.`,
    ].join('\n');

    fs.appendFileSync(engineFile, block + '\n');
}

// ── Main scaffold ─────────────────────────────────────────────────────────────

export function scaffold(choices: UserChoices, targetDir: string): void {
    if (fs.existsSync(targetDir)) {
        throw new Error(`Directory already exists: ${targetDir}`);
    }

    const isLayered = LAYERED.includes(choices.architecture);

    // 1. Base layer — always copied
    const baseDir = path.join(BASE_DIR, choices.architecture);
    if (!fs.existsSync(baseDir)) {
        throw new Error(`Base template not found: ${choices.architecture} (in ${baseDir})`);
    }
    copyDir(baseDir, targetDir);

    // 2. Deploy layer — overlaid on top of base (layered architectures only)
    if (isLayered && choices.deployMode && choices.deployMode !== 'library') {
        const deployDir = path.join(DEPLOY_DIR, choices.deployMode);
        if (!fs.existsSync(deployDir)) {
            throw new Error(`Deploy template not found: ${choices.deployMode} (in ${deployDir})`);
        }
        copyDir(deployDir, targetDir);
    }

    // 3. Skill packs — appended to engine.ts
    for (const pack of choices.skillPacks) {
        injectSkillPack(targetDir, pack);
    }

    // 4. Patch package.json (name + deploy-mode script adjustments)
    patchPackageJson(
        targetDir,
        choices.projectName,
        isLayered ? choices.deployMode : undefined,
    );

    // 5. .env stub
    writeEnv(targetDir, choices.provider);
}

export function installDeps(targetDir: string): void {
    execSync('npm install', { cwd: targetDir, stdio: 'inherit' });
}
