import * as fs from 'node:fs/promises';
import * as path from 'node:path';
import * as yaml from 'yaml';
import { atomicWrite } from '@backendkit-labs/agent-core';
import type { ApprovedRule, RuleStore } from '@backendkit-labs/agent-core';

/** How a rule has fared where it was applied: the evidence a person uses to withdraw it. */
export interface RuleOutcomes {
    success: number;
    failure: number;
    lastSeen: string;
}

interface Entry {
    id: string;
    name?: string;
    if?: unknown;
    then?: unknown;
    trigger?: unknown;
    approvedBy?: ApprovedRule['approvedBy'];
    approvedAt?: string;
    createdAt?: string;
    source?: string;
    reason?: string;
    autoGenerated?: boolean;
    outcomes?: RuleOutcomes;
    [key: string]: unknown;
}

const LEGACY_APPROVER: ApprovedRule['approvedBy'] = { kind: 'service', id: 'legacy-manifest' };

/**
 * The approved rules in a YAML file inside the vault, so they are auditable and versionable with git. It reads and
 * writes the `policyRules` list of the `manifest.yaml` that the previous reflection wrote: the rules already there
 * keep working, and the other keys of the file are left alone.
 */
export class VaultRuleStore implements RuleStore {
    constructor(private readonly filePath: string) {}

    async add(rule: ApprovedRule): Promise<void> {
        const { doc, entries } = await this.read();
        const body = (rule.rule ?? {}) as Record<string, unknown>;
        const entry: Entry = {
            id: rule.id,
            ...(typeof body.name === 'string' ? { name: body.name } : {}),
            if: body.if,
            then: body.then,
            ...(body.trigger ? { trigger: body.trigger } : {}),
            autoGenerated: false,
            approvedBy: rule.approvedBy,
            approvedAt: rule.approvedAt,
            source: rule.source,
            ...(rule.reason ? { reason: rule.reason } : {}),
        };
        const i = entries.findIndex(e => e.id === rule.id);
        if (i >= 0) entries[i] = { ...entries[i], ...entry }; else entries.push(entry);
        await this.write(doc, entries);
    }

    async list(): Promise<ApprovedRule[]> {
        const { entries } = await this.read();
        return entries.filter(e => e.id).map(e => ({
            id: e.id,
            rule: { ...(e.name ? { name: e.name } : {}), if: e.if, then: e.then, ...(e.trigger ? { trigger: e.trigger } : {}) },
            approvedBy: e.approvedBy ?? LEGACY_APPROVER,
            approvedAt: e.approvedAt ?? e.createdAt ?? '',
            source: e.source ?? 'manifest.yaml',
            ...(e.reason ? { reason: e.reason } : {}),
        }));
    }

    async remove(id: string): Promise<boolean> {
        const { doc, entries } = await this.read();
        const rest = entries.filter(e => e.id !== id);
        if (rest.length === entries.length) return false;
        await this.write(doc, rest);
        return true;
    }

    /** Counts one more success or failure where the rule was applied. */
    async recordOutcome(id: string, outcome: 'success' | 'failure'): Promise<boolean> {
        const { doc, entries } = await this.read();
        const entry = entries.find(e => e.id === id);
        if (!entry) return false;
        const current = entry.outcomes ?? { success: 0, failure: 0, lastSeen: '' };
        entry.outcomes = { ...current, [outcome]: current[outcome] + 1, lastSeen: new Date().toISOString() };
        await this.write(doc, entries);
        return true;
    }

    async outcomes(id: string): Promise<RuleOutcomes | undefined> {
        return (await this.read()).entries.find(e => e.id === id)?.outcomes;
    }

    private async read(): Promise<{ doc: Record<string, unknown>; entries: Entry[] }> {
        let text: string;
        try {
            text = await fs.readFile(this.filePath, 'utf8');
        } catch (err) {
            if ((err as NodeJS.ErrnoException).code === 'ENOENT') return { doc: {}, entries: [] };
            throw err;
        }
        const doc = (yaml.parse(text) ?? {}) as Record<string, unknown>;
        return { doc, entries: Array.isArray(doc.policyRules) ? doc.policyRules as Entry[] : [] };
    }

    private async write(doc: Record<string, unknown>, entries: Entry[]): Promise<void> {
        await fs.mkdir(path.dirname(this.filePath), { recursive: true });
        await atomicWrite(this.filePath, yaml.stringify({ ...doc, policyRules: entries }));
    }
}
