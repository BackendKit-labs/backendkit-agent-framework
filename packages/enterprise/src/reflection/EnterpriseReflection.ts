import * as path from 'node:path';
import {
    ReflectionEngine,
    DomainRegistry,
} from '@backendkit-labs/agent-core';
import type { FailureRecord, DetectedPattern, ManifestPolicyRule } from '@backendkit-labs/agent-core/reflection';
import type { GateRecord } from '../flow/ComplianceGate.js';
import { ENTERPRISE_DOMAINS, SEVERITY_THRESHOLD } from './domains.js';
import { recordGateOutcome } from './GateReflectionBridge.js';

// ── Types ─────────────────────────────────────────────────────────────────────

export interface EnterpriseReflectionOptions {
    /** Absolute path to the Obsidian vault. Generated manifest lives inside it. */
    vaultPath: string;
    /**
     * App name for the catalog scope.
     * MUST differ from 'deepseek-code' to avoid collision with the coding agent.
     * Default: 'bk-enterprise'
     */
    appName?: string;
    /**
     * Override path for manifest.yaml.
     * Default: {vaultPath}/politicas/_generated/manifest.yaml
     */
    manifestPath?: string;
}

export interface PendingPromotion {
    pattern:   DetectedPattern;
    detectedAt: string;
}

// ── EnterpriseReflection ──────────────────────────────────────────────────────

/**
 * Adapter that wires the ReflectionEngine (from agent-core, built for coding
 * agents) to enterprise business agents — without modifying agent-core.
 *
 * Key differences vs the coding-agent usage:
 *   - Isolated catalog: appName='bk-enterprise', useGlobalDir=false
 *   - autoPromote=false: every promotion requires human approval
 *   - Threshold by severity: critical=1, high=2, medium/low=3
 *   - Source of incidents: ComplianceGate (evaluator≠executor guaranteed)
 *   - manifest.yaml lives inside the vault (auditable, versionable via git)
 */
export class EnterpriseReflection {
    private readonly engine:        ReflectionEngine;
    private readonly registry:      DomainRegistry;
    private readonly manifestPath:  string;
    private readonly activeDomains: string[];
    private          initialized    = false;

    // Pending promotions accumulate here until a human approves or rejects.
    // Keyed by `${domain}::${failureType}` to deduplicate across detect() calls.
    private readonly pendingMap = new Map<string, PendingPromotion>();

    constructor(opts: EnterpriseReflectionOptions) {
        const appName      = opts.appName ?? 'bk-enterprise';
        this.manifestPath  = opts.manifestPath
            ?? path.join(opts.vaultPath, 'politicas', '_generated', 'manifest.yaml');
        this.activeDomains = ENTERPRISE_DOMAINS.map(d => d.name);

        this.registry = new DomainRegistry({ appName });

        this.engine = new ReflectionEngine({
            appName,
            useGlobalDir: false,   // scoped per project — never touches deepseek-code dirs
            registry:     this.registry,
            config: {
                enabled:              true,
                autoPromote:          false,                // gate humano obligatorio
                promotionThreshold:   3,                   // overridden per-call in detect()
                maxAutoGeneratedRules: 100,
                autoGenerateAdr:      false,
                activeDomains:        this.activeDomains,
                manifestPath:         this.manifestPath,
            },
        });
    }

    // ── Lifecycle ─────────────────────────────────────────────────────────────

    /**
     * Must be called once before any other method.
     * Registers enterprise domains in the DomainRegistry and initializes
     * the engine catalog from disk.
     */
    async initialize(): Promise<void> {
        if (this.initialized) return;

        // Register enterprise domains (idempotent — updateDomain if already exists)
        for (const domain of ENTERPRISE_DOMAINS) {
            const existing = this.registry.getCustomDomain(domain.name);
            if (existing) {
                await this.registry.updateDomain(domain.name, {
                    description:  domain.description,
                    failureTypes: domain.failureTypes,
                });
            } else {
                await this.registry.registerDomain(domain as Parameters<typeof this.registry.registerDomain>[0]);
            }
            await this.registry.enableDomain(domain.name);
        }

        await this.engine.initialize();
        this.initialized = true;
    }

    // ── MONITOR ───────────────────────────────────────────────────────────────

    /**
     * Records the outcome of a resolved ComplianceGate.
     * Only failed criteria and process violations generate incidents.
     * Passed gates produce no catalog entries.
     */
    async recordGateOutcome(record: GateRecord): Promise<FailureRecord[]> {
        this.assertInitialized();
        const { incidents } = await recordGateOutcome(record, this.engine);
        return incidents;
    }

    // ── ANALYZE ───────────────────────────────────────────────────────────────

    /**
     * Scans for patterns using per-severity thresholds.
     * Does NOT promote — patterns accumulate in pendingPromotions() for human review.
     */
    async detect(domain?: string): Promise<DetectedPattern[]> {
        this.assertInitialized();
        const detector = this.engine.getDetector();
        const domains  = domain ? [domain] : this.activeDomains;
        const out: DetectedPattern[] = [];

        for (const d of domains) {
            const domainDef = ENTERPRISE_DOMAINS.find(dd => dd.name === d);
            if (!domainDef) continue;

            for (const ft of domainDef.failureTypes) {
                const threshold = SEVERITY_THRESHOLD[ft.severity] ?? 3;
                const patterns  = await detector.scanByFailureType(d, ft.name, threshold);
                for (const p of patterns) {
                    if (!p.promotedToPolicy) {
                        // Accumulate in pending map — deduplicate
                        const key = `${p.domain}::${p.failureType}`;
                        if (!this.pendingMap.has(key)) {
                            this.pendingMap.set(key, { pattern: p, detectedAt: new Date().toISOString() });
                        }
                    }
                    out.push(p);
                }
            }
        }

        return out;
    }

    // ── PLAN / EXECUTE (human gate on promotion) ──────────────────────────────

    /**
     * Returns patterns that crossed the promotion threshold but haven't been
     * promoted yet (autoPromote=false). Show these to the human approver.
     */
    async pendingPromotions(): Promise<PendingPromotion[]> {
        this.assertInitialized();
        // Re-scan to pick up any new patterns since last detect() call
        await this.detect();
        return Array.from(this.pendingMap.values());
    }

    /**
     * Promotes a detected pattern to a deterministic policyRule in manifest.yaml.
     * Requires an explicit approver identity — logged in the manifest metadata.
     *
     * After approval the pattern is removed from pendingPromotions().
     */
    async approvePromotion(pattern: DetectedPattern, approver: string): Promise<ManifestPolicyRule> {
        this.assertInitialized();
        const promoter = this.engine.getPromoter();

        // Check if a rule already exists for this pattern (idempotent)
        const existing = await promoter.findRule(pattern.domain, pattern.failureType);
        const rule = await promoter.promote(pattern, existing?.id);

        // Tag the rule with the approver (manifest.yaml metadata extension)
        await this.annotateApproval(rule.id, approver, 'approved');

        // Remove from pending
        this.pendingMap.delete(`${pattern.domain}::${pattern.failureType}`);
        return rule;
    }

    /**
     * Rejects a promotion — removes from pending without writing to manifest.
     * The reason is stored as a resolved-but-not-promoted audit note.
     */
    async rejectPromotion(
        pattern:  DetectedPattern,
        approver: string,
        reason:   string,
    ): Promise<void> {
        this.assertInitialized();
        this.pendingMap.delete(`${pattern.domain}::${pattern.failureType}`);
        // Record the rejection as a meta-incident so it appears in stats
        await this.engine.reportIncident({
            domain:            'agent',
            failureType:       'promotion_rejected',
            severity:          'low',
            dimension:         'proceso',
            gate:              'reflection-promotion',
            agenteResponsable: approver,
            hallazgo:          `Promotion rejected for ${pattern.domain}::${pattern.failureType} — ${reason}`,
            recomendacion:     'Review pattern manually to decide if a manual policy rule is needed',
            archivos:          [],
            fecha:             new Date().toISOString(),
        });
    }

    // ── KNOWLEDGE (consumed by executor) ──────────────────────────────────────

    /**
     * Returns active policyRules from manifest.yaml, optionally filtered by domain.
     * Call this BEFORE executing a step to inject deterministic constraints.
     */
    async activeRules(filter?: { domain?: string }): Promise<ManifestPolicyRule[]> {
        this.assertInitialized();
        const promoter = this.engine.getPromoter();
        const all = await promoter.getExistingRules();
        if (!filter?.domain) return all;
        return all.filter(r => r.trigger.domain === filter.domain);
    }

    /**
     * Records whether applying a rule led to a successful or failed outcome.
     * Outcomes feed demotionCandidates() — rules with many failures signal
     * that the rule itself may be wrong.
     */
    async recordRuleOutcome(ruleId: string, outcome: 'success' | 'failure'): Promise<void> {
        this.assertInitialized();
        await this.engine.getPromoter().updateOutcome(ruleId, outcome);
    }

    /**
     * Returns rules whose failure rate exceeds minFailureRatio (default 0.5)
     * with at least minTotal applications (default 4).
     *
     * These are candidates for human-gated demotion — symmetric with promotion:
     * the rulebook only changes in either direction with human approval.
     */
    async demotionCandidates(opts: { minFailureRatio?: number; minTotal?: number } = {}): Promise<ManifestPolicyRule[]> {
        this.assertInitialized();
        const { minFailureRatio = 0.5, minTotal = 4 } = opts;
        const rules = await this.engine.getPromoter().getExistingRules();
        return rules.filter(r => {
            const outcomes = r.outcomes;
            if (!outcomes) return false;
            const total = outcomes.success + outcomes.failure;
            if (total < minTotal) return false;
            return outcomes.failure / total >= minFailureRatio;
        });
    }

    /**
     * Removes a rule from manifest.yaml after human approval of demotion.
     * Symmetric with approvePromotion — requires explicit approver.
     */
    async approveDemotion(ruleId: string, approver: string, reason: string): Promise<boolean> {
        this.assertInitialized();
        const removed = await this.engine.getPromoter().removeRule(ruleId);
        if (removed) {
            await this.engine.reportIncident({
                domain:            'agent',
                failureType:       'rule_demoted',
                severity:          'low',
                dimension:         'proceso',
                gate:              'reflection-demotion',
                agenteResponsable: approver,
                hallazgo:          `Rule ${ruleId} demoted — ${reason}`,
                recomendacion:     'Monitor for recurrence of the underlying failure type',
                archivos:          [],
                fecha:             new Date().toISOString(),
            });
        }
        return removed;
    }

    // ── Stats ─────────────────────────────────────────────────────────────────

    async stats() {
        this.assertInitialized();
        return this.engine.getStats();
    }

    // ── Private ───────────────────────────────────────────────────────────────

    private assertInitialized(): void {
        if (!this.initialized) {
            throw new Error('EnterpriseReflection not initialized — call initialize() first');
        }
    }

    private async annotateApproval(ruleId: string, approver: string, action: 'approved' | 'demoted'): Promise<void> {
        // The manifest.yaml doesn't have a native approver field in ManifestPolicyRule,
        // so we write a companion meta-incident that creates an auditable trail.
        await this.engine.reportIncident({
            domain:            'agent',
            failureType:       `rule_${action}`,
            severity:          'low',
            dimension:         'proceso',
            gate:              'reflection-promotion',
            agenteResponsable: approver,
            hallazgo:          `Policy rule ${ruleId} ${action} by ${approver}`,
            recomendacion:     '',
            archivos:          [this.manifestPath],
            fecha:             new Date().toISOString(),
        });
    }
}
