import * as fs from 'fs/promises';
import * as path from 'path';
import * as yaml from 'yaml';
import { run, isOk, fromThrowable } from '@backendkit-labs/result';
import { getFrameworkDir } from '@backendkit-labs/agent-core';
import { isProjectTrusted } from '../trust/workspace-trust';
import { parseMdSkill } from './parse-md-skill';
import type { Skill, SkillScope } from '@backendkit-labs/agent-core';

export interface LoadedSkills {
    global: Skill[];
    packs: Skill[];
    projectConfig: Skill[];  // ~/.{app}/projects/{key}/skills/ — generated, not git-tracked
    project: Skill[];        // {cwd}/.{app}/skills/ — manual, git-tracked
}

const SKILL_FILE_RE = /\.(ya?ml|md)$/i;

/**
 * Loads skills from the 4-layer hierarchy.
 * Supports both .yaml/.yml (legacy) and .md (with frontmatter) skill files.
 *
 * Layer structure (appName = 'bk-agent'):
 *   ~/.bk-agent/skills/global/        ← language-agnostic, loaded for every project
 *   ~/.bk-agent/skills/packs/{pack}/  ← installed language packs
 *   ~/.bk-agent/projects/{key}/skills/← auto-generated skills (not git-tracked)
 *   {cwd}/.bk-agent/skills/           ← project-specific, git-tracked
 *
 * On a name collision, precedence is project > projectConfig > pack > global > builtin.
 * When both .yaml and .md exist for the same skill name, .md wins.
 */
export class SkillLoader {
    constructor(private readonly appName: string) {}

    async loadGlobal(): Promise<Skill[]> {
        const dir = path.join(getFrameworkDir(this.appName), 'skills', 'global');
        return this.loadFromDir(dir, 'global');
    }

    async loadPacks(): Promise<Skill[]> {
        const packsDir = path.join(getFrameworkDir(this.appName), 'skills', 'packs');
        const accessResult = await run(() => fs.access(packsDir));
        if (!isOk(accessResult)) return [];

        const entries = await run(() => fs.readdir(packsDir, { withFileTypes: true }));
        if (!isOk(entries)) return [];

        const skills: Skill[] = [];
        for (const entry of entries.value) {
            if (!entry.isDirectory()) continue;
            const packDir = path.join(packsDir, entry.name);
            const packSkills = await this.loadFromDir(packDir, 'pack', entry.name);
            skills.push(...packSkills);
        }
        return skills;
    }

    /**
     * Loads project-specific skills from inside the project directory.
     * Path: {cwd}/.{appName}/skills/*.{yaml,yml,md}
     *
     * These come from the repository, so they load only when the project is trusted (ADR-0006); otherwise this
     * returns nothing. `trusted` lets a host that already decided pass its answer instead of asking again.
     */
    async loadProject(cwd: string, trusted: boolean = isProjectTrusted(this.appName, cwd).trusted): Promise<Skill[]> {
        if (!trusted) return [];
        const dir = path.join(cwd, `.${this.appName}`, 'skills');
        return this.loadFromDir(dir, 'project');
    }

    /**
     * Loads auto-generated skills from ~/.{appName}/projects/{key}/skills/.
     * These are generated by LearningRouter — not git-tracked.
     */
    async loadProjectConfig(projectDir: string): Promise<Skill[]> {
        const dir = path.join(projectDir, 'skills');
        return this.loadFromDir(dir, 'project');
    }

    async loadAll(cwd?: string, projectDir?: string, trusted?: boolean): Promise<LoadedSkills> {
        const [global, packs, projectConfig, project] = await Promise.all([
            this.loadGlobal(),
            this.loadPacks(),
            projectDir ? this.loadProjectConfig(projectDir) : Promise.resolve([]),
            cwd ? this.loadProject(cwd, trusted) : Promise.resolve([]),
        ]);
        return { global, packs, projectConfig, project };
    }

    private async loadFromDir(
        dir: string,
        scope: SkillScope,
        pack?: string,
    ): Promise<Skill[]> {
        const accessResult = await run(() => fs.access(dir));
        if (!isOk(accessResult)) return [];

        const filesResult = await run(() => fs.readdir(dir));
        if (!isOk(filesResult)) return [];

        // Sort so .yaml/.yml are processed before .md — .md overwrites on name collision
        const files = filesResult.value
            .filter(f => SKILL_FILE_RE.test(f))
            .sort((a, b) => {
                const aIsMd = /\.md$/i.test(a);
                const bIsMd = /\.md$/i.test(b);
                if (aIsMd === bIsMd) return 0;
                return aIsMd ? 1 : -1; // .md last → wins on Map.set
            });

        const byName = new Map<string, Skill>();
        for (const file of files) {
            const filePath = path.join(dir, file);
            const contentResult = await run(() => fs.readFile(filePath, 'utf-8'));
            if (!isOk(contentResult)) continue;

            const skill = /\.md$/i.test(file)
                ? parseMdSkill(contentResult.value)
                : parseYamlSkill(contentResult.value);

            if (!skill?.name) continue;

            byName.set(skill.name, { ...skill, scope, ...(pack ? { pack } : {}) });
        }

        return Array.from(byName.values());
    }
}

function parseYamlSkill(content: string): Skill | null {
    const parsed = fromThrowable(() => yaml.parse(content) as Skill);
    if (!parsed.ok || !parsed.value?.name) return null;
    const skill = parsed.value;
    if (!Array.isArray(skill.triggers)) skill.triggers = [];
    return skill;
}
