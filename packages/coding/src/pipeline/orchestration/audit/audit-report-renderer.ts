/**
 * @description AuditReportRenderer — Renderiza informes Markdown de auditoría.
 *
 * Responsabilidades:
 * - Renderizar informe de gate individual (renderGateReport)
 * - Renderizar informe final multi-gate (renderFinalReport)
 * - Construir resumen ejecutivo (buildExecutiveSummary)
 * - Calcular hash SHA-256 de integridad
 */

import * as crypto from 'crypto';
import { TaskContext } from '../task-context';
import {
  AuditFinding,
  GateRecord,
  GateVeredict,
  SprintInfo,
  FinalReport,
} from './types';

// ── Helpers ──────────────────────────────────────────────────────────────────

function calculateHash(content: string): string {
  return crypto.createHash('sha256').update(content, 'utf-8').digest('hex');
}

// ── AuditReportRenderer ──────────────────────────────────────────────────────

export class AuditReportRenderer {
  /**
   * @description Renderiza un informe de gate individual en Markdown.
   */
  renderGateReport(
    record: GateRecord,
    version: string,
    fecha: string,
    task?: TaskContext
  ): string {
    const findingsTable = record.hallazgos.length > 0
      ? `| ID | Dimension | Finding | Severity | Evidence | Recommendation | Responsible Agent |\n` +
        `|----|-----------|---------|----------|----------|----------------|-------------------|\n` +
        record.hallazgos.map(h =>
          `| ${h.id} | ${h.dimension} | ${h.hallazgo} | **${h.severidad}** | ${h.evidencia} | ${h.recomendacion} | ${h.agenteResponsable} |`
        ).join('\n')
      : '*No findings*';

    const content = `---
title: "Gate Report: ${record.gate}"
version: "${version}"
date: "${fecha}"
type: "gate"
auditor: "${record.agente}"
verdict: "${record.veredicto}"
tags:
  - audit
  - gate
  - ${record.gate.toLowerCase().replace(/\s+/g, '-')}
---

# 📋 Gate Report: ${record.gate}

> **Auditor:** ${record.agente}
> **Date:** ${fecha}
> **Report version:** ${version}
> **Verdict:** ${record.veredicto === 'GO' ? '✅ APPROVED' : record.veredicto === 'NO-GO condicional' ? '⚠️ CONDITIONALLY APPROVED' : '❌ NOT APPROVED'}

---

## Findings Matrix

${findingsTable}

${record.notas ? `\n## Notes\n\n${record.notas}\n` : ''}
${task ? `## Task Context\n\n- **Prompt:** ${task.rawPrompt}\n- **Type:** ${task.actionType}\n- **Domain(s):** ${task.domains.join(', ')}\n- **Risk Level:** ${task.riskLevel}\n` : ''}

---

*Auto-generated by the audit pipeline*
`;

    return this.wrapWithIntegrity(content, version, fecha);
  }

  /**
   * @description Renderiza el informe final multi-gate en Markdown.
   */
  renderFinalReport(report: FinalReport, version: string, fecha: string): string {
    const findingsMatrix = report.gates.flatMap(g =>
      g.hallazgos.map(h => ({ gate: g.gate, ...h }))
    );

    const reportContentForHash = JSON.stringify(report);
    const totalHash = calculateHash(reportContentForHash);

    const findingsTable = findingsMatrix.length > 0
      ? `| ID | Gate | Dimension | Finding | Severity | Evidence | Recommendation | Agent |\n` +
        `|----|------|-----------|---------|----------|----------|----------------|-------|\n` +
        findingsMatrix.map(h =>
          `| ${h.id} | ${h.gate} | ${h.dimension} | ${h.hallazgo} | **${h.severidad}** | ${h.evidencia} | ${h.recomendacion} | ${h.agenteResponsable} |`
        ).join('\n')
      : '*No findings across any gate*';

    const riesgosTable = report.riesgos.length > 0
      ? `| Risk | Probability | Impact | Mitigation |\n` +
        `|------|-------------|--------|------------|\n` +
        report.riesgos.map(r => `| ${r.riesgo} | ${r.probabilidad} | ${r.impacto} | ${r.mitigacion} |`).join('\n')
      : '*No accumulated risks*';

    const inmediatos = findingsMatrix.filter(h => h.severidad === 'critical' || h.severidad === 'high');
    const cortoPlazo = findingsMatrix.filter(h => h.severidad === 'medium');
    const medioPlazo = findingsMatrix.filter(h => h.severidad === 'low');

    const remediacion = `
### 🔴 Immediate (${inmediatos.length})
${inmediatos.length > 0
  ? inmediatos.map(h => `- **${h.id}** (${h.gate}): ${h.hallazgo} → ${h.recomendacion} (_${h.agenteResponsable}_)`).join('\n')
  : '*No critical or high findings pending*'}

### 🟡 Short term (${cortoPlazo.length})
${cortoPlazo.length > 0
  ? cortoPlazo.map(h => `- **${h.id}** (${h.gate}): ${h.hallazgo} → ${h.recomendacion}`).join('\n')
  : '*No medium findings pending*'}

### 🟢 Medium term (${medioPlazo.length})
${medioPlazo.length > 0
  ? medioPlazo.map(h => `- **${h.id}** (${h.gate}): ${h.hallazgo} → ${h.recomendacion}`).join('\n')
  : '*No low findings pending*'}
`;

    const veredictoBlock = report.veredictoFinal === 'GO'
      ? `\`\`\`\n┌─────────────────────────────────────────────────────────────┐\n│                                                             │\n│   ✅   ✅   ✅   ✅                                         │\n│  🏷️  🏗️  🔐  🔍                                         │\n│                                                             │\n│              🚀 READY TO COMMIT                             │\n│                                                             │\n│  Sprint: ${report.sprint.name}                              │\n│  ${report.sprint.newFiles.length + report.sprint.modifiedFiles.length} files · 0 blockers · 0 vulnerabilities       │\n│                                                             │\n└─────────────────────────────────────────────────────────────┘\n\`\`\``
      : `\`\`\`\n┌─────────────────────────────────────────────────────────────┐\n│                                                             │\n│   ⚠️   ⚠️   ⚠️                                             │\n│  🏷️  🏗️  🔐  🔍                                         │\n│                                                             │\n│           ⛔ NOT READY TO COMMIT                            │\n│                                                             │\n│  Sprint: ${report.sprint.name}                              │\n│  ${inmediatos.length} blocker(s) · ${cortoPlazo.length} pending          │\n│                                                             │\n└─────────────────────────────────────────────────────────────┘\n\`\`\``;

    const content = `---
title: "Final Multi-Gate Report: ${report.sprint.name}"
version: "${version}"
date: "${fecha}"
type: "final-report"
sprint: "${report.sprint.name}"
verdict: "${report.veredictoFinal}"
hash_total: "${totalHash}"
tags:
  - audit
  - final-report
  - ${report.sprint.name.toLowerCase().replace(/\s+/g, '-')}
---

# 📋 Final Multi-Gate Report
## Sprint: ${report.sprint.name}

> **Project version:** ${report.sprint.version}
> **Report version:** ${version}
> **Report date:** ${fecha}
> **SHA-256 total:** \`${totalHash}\`
> **Sprint purpose:** ${report.sprint.purpose}

---

${this.buildExecutiveSummary(report.sprint, report.veredictoFinal, report.gates)}

---

## 📊 Findings Matrix by Dimension

${findingsTable}

---

## 📈 Top ${Math.min(report.riesgos.length, 5)} Accumulated Risks

${riesgosTable}

---

## 🛠️ Prioritized Remediation Plan

${remediacion}

---

## ✅ Final Multi-Gate Verdict

${veredictoBlock}

### Summary for Commit Message

\`\`\`
${report.sprint.name}: ${report.sprint.purpose}

${report.sprint.newFiles.map(f => `- ${f}`).join('\n')}
${report.sprint.modifiedFiles.map(f => `- ${f}`).join('\n')}
\`\`\`

---

## 📎 Gate History

| Date | Gate | Auditor | Verdict |
|------|------|---------|---------|
${report.gates.map(g => `| ${g.fecha} | ${g.gate} | ${g.agente} | ${g.veredicto} |`).join('\n')}

---

*Auto-generated by the audit pipeline*
*Participating agents: ${[...new Set(report.gates.map(g => g.agente))].join(', ')}*
*Last updated: ${report.fecha} UTC*
`;

    return this.wrapWithIntegrity(content, version, fecha);
  }

  // ── Resumen Ejecutivo ─────────────────────────────────────────────────────

  /**
   * @description Construye el resumen ejecutivo del sprint.
   */
  buildExecutiveSummary(sprint: SprintInfo, veredictoFinal: GateVeredict, gates: GateRecord[]): string {
    const gatesSummary = gates.map(g =>
      `| ${g.gate} | ${g.veredicto === 'GO' ? '✅' : g.veredicto === 'NO-GO condicional' ? '⚠️' : '❌'} ${g.veredicto} | ${g.agente} |`
    ).join('\n');

    return `
## 🧭 Executive Summary

| Gate | Status | Auditor |
|------|--------|---------|
${gatesSummary}
| 🚀 **Final Verdict** | **${veredictoFinal === 'GO' ? '✅ READY TO COMMIT' : veredictoFinal === 'NO-GO condicional' ? '⚠️ CONDITIONAL NO-GO' : '❌ NO-GO'}** | — |

### 📦 Sprint Changes (${sprint.newFiles.length + sprint.modifiedFiles.length} files)

**Purpose:** ${sprint.purpose}

**🔵 New files (${sprint.newFiles.length}):**
${sprint.newFiles.map(f => `- \`${f}\``).join('\n')}

**🟡 Modified files (${sprint.modifiedFiles.length}):**
${sprint.modifiedFiles.map(f => `- \`${f}\``).join('\n')}

**🧪 Tests:** ${sprint.testCount} tests · ${sprint.testTime}
`;
  }

  // ── Integridad ─────────────────────────────────────────────────────────────

  /**
   * @description Envuelve el contenido con hash SHA-256 y metadatos de integridad.
   */
  private wrapWithIntegrity(content: string, version: string, fecha: string): string {
    const hash = calculateHash(content);
    return `**SHA-256:** \`${hash}\`  \n**Report version:** ${version}  \n**Date:** ${fecha}  \n\n---\n\n${content}`;
  }
}
