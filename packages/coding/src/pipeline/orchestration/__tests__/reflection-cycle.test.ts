/**
 * Integration test: PolicyPromoter → manifest.yaml → Orchestrator.loadManifestPolicyRules → applyPolicies
 *
 * Verifies the closed feedback loop:
 *   1. ReflectionEngine promotes a detected pattern to manifest.yaml via PolicyPromoter
 *   2. Orchestrator reads manifest.yaml on every orchestrate() call (PolicyStep)
 *   3. The promoted rule fires for matching input and enriches the task context
 */

import * as os from 'os';
import * as path from 'path';
import * as fs from 'fs/promises';
import * as yaml from 'yaml';
import { PolicyPromoter } from '@backendkit-labs/agent-core';
import { Orchestrator } from '../orchestrator';
import { evaluatePolicies } from '../policy-engine';
import type { DetectedPattern } from '@backendkit-labs/agent-core';
import type { OrchestratorConfig } from '../types';

// ── Fixtures ──────────────────────────────────────────────────────────────────

let tmpHome: string;
const APP_NAME = 'test-reflection-app';

beforeEach(async () => {
    tmpHome = await fs.mkdtemp(path.join(os.tmpdir(), 'reflection-cycle-'));
    process.env.USERPROFILE = tmpHome;
    process.env.HOME = tmpHome;
});

afterEach(async () => {
    await fs.rm(tmpHome, { recursive: true, force: true });
    delete process.env.USERPROFILE;
    delete process.env.HOME;
});

function manifestPath(): string {
    return path.join(tmpHome, `.${APP_NAME}`, 'manifest.yaml');
}

function makePattern(overrides: Partial<DetectedPattern> = {}): DetectedPattern {
    return {
        domain: 'audit',
        failureType: 'security_vulnerability',
        count: 4,
        severity: 'high',
        firstSeen: new Date().toISOString(),
        lastSeen: new Date().toISOString(),
        recordIds: [],
        dominantDimension: 'security',
        dominantGate: 'qa',
        recommendedAction: 'Add security review',
        promotedToPolicy: false,
        ...overrides,
    };
}

/** Minimal orchestrator config with only policyEngine enabled (no LLM steps). */
const MINIMAL_CONFIG: OrchestratorConfig = {
    features: {
        intentDetection: false,
        domainDetection: false,
        riskScoring: false,
        policyEngine: true,
        fsm: false,
        qaGate: false,
        commitGate: false,
    },
    riskThresholds: { low: 10, medium: 30, high: 60, critical: 80 },
    riskWeights: {
        breaking_change: 25,
        security_sensitive: 30,
        cross_service_impact: 20,
        db_transactional: 15,
        production_critical: 25,
        complexity: 1,
    },
};

// ── PolicyPromoter ────────────────────────────────────────────────────────────

describe('PolicyPromoter — writes manifest.yaml', () => {
    it('creates manifest.yaml with a policyRules entry', async () => {
        const promoter = new PolicyPromoter({ appName: APP_NAME });
        const rule = await promoter.promote(makePattern());

        expect(rule.id).toMatch(/^POL-AUDI-\d+$/);
        expect(rule.autoGenerated).toBe(true);

        const content = await fs.readFile(manifestPath(), 'utf-8');
        const manifest = yaml.parse(content);
        expect(manifest.policyRules).toHaveLength(1);
        expect(manifest.policyRules[0].id).toBe(rule.id);
    });

    it('promoted rule has if.keywords derived from the failureType', async () => {
        const promoter = new PolicyPromoter({ appName: APP_NAME });
        const rule = await promoter.promote(makePattern({ failureType: 'security_vulnerability' }));

        // Keywords for 'security_vulnerability' include 'auth', 'jwt', 'seguridad'
        expect(rule.if.keywords).toBeDefined();
        expect((rule.if.keywords as string[]).length).toBeGreaterThan(0);
    });

    it('idempotent — promoting same pattern twice updates, does not duplicate', async () => {
        const promoter = new PolicyPromoter({ appName: APP_NAME });
        const rule1 = await promoter.promote(makePattern({ failureType: 'jest_timeout', domain: 'test' }));
        await promoter.promote(makePattern({ failureType: 'jest_timeout', domain: 'test' }), rule1.id);

        const manifest = await promoter.readManifest();
        const rules: Array<{ id: string }> = manifest.policyRules ?? [];
        expect(rules.filter(r => r.id === rule1.id)).toHaveLength(1);
    });

    it('accumulates multiple distinct patterns as separate rules', async () => {
        const promoter = new PolicyPromoter({ appName: APP_NAME });
        await promoter.promote(makePattern({ failureType: 'missing_rollback' }));
        await promoter.promote(makePattern({ domain: 'test', failureType: 'coverage_below_threshold', severity: 'medium' }));

        const rules = await promoter.getExistingRules();
        expect(rules).toHaveLength(2);
    });

    it('updateOutcome records success/failure counts', async () => {
        const promoter = new PolicyPromoter({ appName: APP_NAME });
        const rule = await promoter.promote(makePattern({ failureType: 'missing_logging', severity: 'medium' }));

        await promoter.updateOutcome(rule.id, 'success');
        await promoter.updateOutcome(rule.id, 'failure');
        await promoter.updateOutcome(rule.id, 'success');

        const updated = await promoter.getRuleById(rule.id);
        expect(updated?.outcomes?.success).toBe(2);
        expect(updated?.outcomes?.failure).toBe(1);
    });

    it('removeRule deletes a rule by id', async () => {
        const promoter = new PolicyPromoter({ appName: APP_NAME });
        const rule = await promoter.promote(makePattern());
        await promoter.removeRule(rule.id);

        const rules = await promoter.getExistingRules();
        expect(rules.find(r => r.id === rule.id)).toBeUndefined();
    });
});

// ── Orchestrator reads manifest on each orchestrate() ─────────────────────────

describe('Orchestrator — loadManifestPolicyRules picks up promoted rules', () => {
    it('applies a manifest rule with keyword matching to the user input', async () => {
        // Write a rule directly to manifest.yaml
        const manifestDir = path.join(tmpHome, `.${APP_NAME}`);
        await fs.mkdir(manifestDir, { recursive: true });
        const rule = {
            id: 'POL-AUDI-001',
            name: 'Test Security Rule',
            if: { keywords: ['vulnerabilidad-test-unica', 'test-security-keyword'] },
            then: { requireQaApproval: true, mustInclude: ['security-agent'] },
            trigger: { domain: 'audit', pattern: 'security_vulnerability', minOccurrences: 3 },
            autoGenerated: true,
            createdAt: new Date().toISOString(),
            engineVersion: '1.0.0',
        };
        await fs.writeFile(
            path.join(manifestDir, 'manifest.yaml'),
            yaml.stringify({ policyRules: [rule] }),
        );

        const orchestrator = new Orchestrator({ appName: APP_NAME, config: MINIMAL_CONFIG });

        const result = await orchestrator.orchestrate('hay una vulnerabilidad-test-unica en el sistema');

        // The promoted rule must fire: qa approval + security agent
        expect(result.task.requiresQaApproval).toBe(true);
        expect(result.selectedAgents.some(a => a.agentId === 'security-agent')).toBe(true);
    });

    it('does not fire a rule when input has no matching keyword', async () => {
        const manifestDir = path.join(tmpHome, `.${APP_NAME}`);
        await fs.mkdir(manifestDir, { recursive: true });
        const rule = {
            id: 'POL-AUDI-001',
            name: 'Specific keyword rule',
            if: { keywords: ['keyword-muy-especifico-xyz'] },
            then: { requireQaApproval: true },
            trigger: { domain: 'audit', pattern: 'security_vulnerability', minOccurrences: 3 },
            autoGenerated: true,
            createdAt: new Date().toISOString(),
            engineVersion: '1.0.0',
        };
        await fs.writeFile(
            path.join(manifestDir, 'manifest.yaml'),
            yaml.stringify({ policyRules: [rule] }),
        );

        const orchestrator = new Orchestrator({ appName: APP_NAME, config: MINIMAL_CONFIG });
        const result = await orchestrator.orchestrate('write a unit test for the login feature');

        const manifestRuleFired = result.appliedPolicies.some(p =>
            p.rule.includes('keyword-muy-especifico-xyz')
        );
        expect(manifestRuleFired).toBe(false);
    });

    it('does not throw when manifest does not exist — returns empty rules', async () => {
        const orchestrator = new Orchestrator({ appName: APP_NAME, config: MINIMAL_CONFIG });
        // No manifest file written — should silently return []
        await expect(orchestrator.orchestrate('simple question')).resolves.toBeDefined();
    });

    it('picks up newly promoted rules on subsequent orchestrate() calls (no caching)', async () => {
        const promoter = new PolicyPromoter({ appName: APP_NAME });
        const orchestrator = new Orchestrator({ appName: APP_NAME, config: MINIMAL_CONFIG });

        // First call — no rules yet
        await expect(orchestrator.orchestrate('transaccion y rollback')).resolves.toBeDefined();

        // Promote a pattern after the first call
        await promoter.promote(makePattern({ failureType: 'missing_rollback' }));

        // Second call — manifest now has the rule; it should load fresh
        const after = await orchestrator.orchestrate('transaccion y rollback');
        expect(after).toBeDefined();

        // Verify the manifest was written with one rule
        const rules = await promoter.getExistingRules();
        expect(rules).toHaveLength(1);
    });
});

// ── evaluatePolicies — unit tests for keyword matching ────────────────────────

describe('evaluatePolicies — keyword matching in manifest-derived rules', () => {
    it('fires a keyword-based rule when input contains a matching keyword', () => {
        const { createTaskContext } = require('../task-context');
        const task = createTaskContext('quiero revisar el jwt token');
        const rules = [
            {
                if: { keywords: ['jwt', 'auth', 'oauth'] },
                then: { requireQaApproval: true, mustInclude: ['security-agent'] },
            },
        ];

        const result = evaluatePolicies(task, rules, 'quiero revisar el jwt token');

        expect(result.requiredGates).toContain('qa');
        expect(result.mustInclude).toContain('security-agent');
    });

    it('does not fire when input has no matching keyword', () => {
        const { createTaskContext } = require('../task-context');
        const task = createTaskContext('refactor the pagination logic');
        const rules = [
            {
                if: { keywords: ['jwt', 'auth', 'oauth'] },
                then: { requireQaApproval: true, mustInclude: ['security-agent'] },
            },
        ];

        const result = evaluatePolicies(task, rules, 'refactor the pagination logic');

        expect(result.mustInclude).not.toContain('security-agent');
    });

    it('keyword matching is case-insensitive', () => {
        const { createTaskContext } = require('../task-context');
        const task = createTaskContext('fix JWT validation');
        const rules = [{ if: { keywords: ['jwt'] }, then: { requireQaApproval: true } }];

        const result = evaluatePolicies(task, rules, 'fix JWT validation');
        expect(result.requiredGates).toContain('qa');
    });

    it('applies multiple rules when all conditions match', () => {
        const { createTaskContext } = require('../task-context');
        const task = createTaskContext('security auth review');
        const rules = [
            { if: { keywords: ['auth'] }, then: { mustInclude: ['security-agent'] } },
            { if: { keywords: ['review'] }, then: { mustInclude: ['qa-engineer'] } },
        ];

        const result = evaluatePolicies(task, rules, 'security auth review');
        expect(result.mustInclude).toContain('security-agent');
        expect(result.mustInclude).toContain('qa-engineer');
    });
});
